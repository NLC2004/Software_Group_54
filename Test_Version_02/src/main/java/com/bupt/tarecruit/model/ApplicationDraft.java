package com.bupt.tarecruit.model;

/**
 * Represents the application draft component of the TA recruitment system.
 */
public class ApplicationDraft {
    /**
     * Stores the id value.
     */
    public String id;
    /**
     * Stores the user id value.
     */
    public String userId;
    /**
     * Stores the job id value.
     */
    public String jobId;
    /**
     * Stores the confirm student id value.
     */
    public String confirmStudentId;
    /**
     * Stores the confirm full name value.
     */
    public String confirmFullName;
    /**
     * Stores the confirm phone value.
     */
    public String confirmPhone;
    /**
     * Stores the confirm gender value.
     */
    public String confirmGender;
    /**
     * Stores the confirm school value.
     */
    public String confirmSchool;
    /**
     * Stores the confirm year value.
     */
    public String confirmYear;
    /**
     * Stores the cover letter value.
     */
    public String coverLetter;
    /**
     * Stores the priority value.
     */
    public int priority;
    /**
     * Stores the resume draft file name value.
     */
    public String resumeDraftFileName;
    /**
     * Stores the created at value.
     */
    public long createdAt;
    /**
     * Stores the updated at value.
     */
    public long updatedAt;

    /**
     * Creates a new application draft instance.
     */
    public ApplicationDraft() {}
}
